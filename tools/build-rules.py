#!/usr/bin/env python3
"""
Build firestore.rules: the Firebase security rules, with the class list built in.

Only students on the class list (plus the lecturer, S000001) can save progress or see the
leaderboard. The rules file contains student emails, so it is NOT committed (see .gitignore):
paste it into Firebase console > Firestore > Rules > Publish.

Usage (same inputs as build-roster.py):
    python3 tools/build-rules.py ClassList_MKT301_*.xls        (or a CSV of IDs)
"""
import importlib.util, sys
from pathlib import Path

here = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("roster", here / "build-roster.py")
roster = importlib.util.module_from_spec(spec); spec.loader.exec_module(roster)

DOMAIN = "student.mnu.edu.mv"
LECTURER = "s000001@" + DOMAIN

TEMPLATE = """rules_version = '2';
// MKT301 Arena security rules. Generated by tools/build-rules.py. Do not commit (contains the class list).
service cloud.firestore {
  match /databases/{database}/documents {
    function signedIn() { return request.auth != null && request.auth.token.email != null; }
    function onRoster() { return signedIn() && request.auth.token.email in [
__EMAILS__
    ]; }
    function isLecturer() { return signedIn() && request.auth.token.email == '__LECTURER__'; }
    function isOwner(sid) { return onRoster() && request.auth.token.email == sid.lower() + '@__DOMAIN__'; }

    // Each student's full progress: only they (and the lecturer) can read it.
    match /users/{sid} {
      allow read: if isOwner(sid) || isLecturer();
      allow create, update: if isOwner(sid)
        && request.resource.data.keys().hasOnly(['name', 'u', 'xp', 'ts'])
        && request.resource.data.name is string && request.resource.data.name.size() <= 80
        && request.resource.data.u is string && request.resource.data.u.size() < 800000
        && request.resource.data.xp is int && request.resource.data.ts == request.time;
      allow delete: if isLecturer();
    }

    // Leaderboard row: everyone on the class list can read; only the owner can write,
    // and XP cannot jump by more than 3,000 in one save.
    function validRow() {
      let d = request.resource.data;
      return d.keys().hasOnly(['n', 'x', 'l', 'b', 's', 't'])
        && d.n is string && d.n.size() <= 24
        && d.x is int && d.x >= 0 && d.x <= 50000
        && d.l is int && d.b is int && d.s is int && d.t == request.time;
    }
    // Marks for typed answers: each student reads only their own; only the lecturer writes
    // (the lecturer dashboard, or Claude marking signed in as the lecturer). m = {answerKey: {q, band, xp, fb, at, by}}.
    match /reviews/{sid} {
      allow read: if isOwner(sid) || isLecturer();
      allow create, update: if isLecturer() && request.resource.data.keys().hasOnly(['m'])
        && request.resource.data.m is map && request.resource.data.m.size() <= 500;
      allow delete: if isLecturer();
    }

    match /board/{sid} {
      allow read: if onRoster();
      allow create: if isOwner(sid) && validRow() && request.resource.data.x <= 5000;
      allow update: if isOwner(sid) && validRow() && request.resource.data.x <= resource.data.x + 3000;
      allow delete: if isOwner(sid) || isLecturer();
    }
  }
}
"""

def main(files):
    if not files: sys.exit(__doc__)
    active = set(roster.ALWAYS)
    for f in files:
        a, _ = roster.ids_from_csv(f) if f.lower().endswith(".csv") else roster.ids_from_classlist(f)
        active |= a
    emails = sorted(s.lower() + "@" + DOMAIN for s in active)
    out = Path.cwd() / "firestore.rules"
    out.write_text(TEMPLATE.replace("__EMAILS__", ",\n".join("      '" + e + "'" for e in emails))
                   .replace("__LECTURER__", LECTURER).replace("__DOMAIN__", DOMAIN), encoding="utf-8")
    print(f"firestore.rules: {len(emails)} emails (including the lecturer). Paste it into Firestore > Rules and Publish.")

if __name__ == "__main__":
    main(sys.argv[1:])
